const COLOURS: Record<string, [string, string]> = {
  coin: ["#d9a21b", "#f2cf62"],
  authority: ["#2a2e8a", "#6c72e0"],
  deed: ["#3f8f5a", "#9a7652"],
  key: ["#9c7b22", "#d8b54a"],
  banner: ["#2a2e8a", "#b3402a"],
  trophy: ["#b8871a", "#f0c94a"],
  wear: ["#4f5a76", "#8f9bb8"],
  face: ["#262c3a", "#8fb3d9"],
  hand: ["#7a5230", "#e8dcc8"],
};

export type GlyphKind = keyof typeof ART | string;

/** A pixel picture of `kind` ("coin", "deed", …); `authority` colours a coin as authority. */
export function Glyph({ kind, authority = false, size = 48 }: { kind: GlyphKind; authority?: boolean; size?: number }) {
  const art = ART[kind] ?? ART.coin!;
  const [a, b] = COLOURS[authority ? "authority" : kind] ?? COLOURS.coin!;
  return (
    <svg viewBox="0 0 12 12" width={size} height={size} aria-hidden="true" shapeRendering="crispEdges" style={{ flex: "none" }}>
      {art.flatMap((row, y) =>
        [...row].map((ch, x) => (ch === "." ? null : <rect key={`${x},${y}`} x={x} y={y} width={1} height={1} fill={ch === "#" ? a : b} />)),
      )}
    </svg>
  );
}
