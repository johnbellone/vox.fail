const COLOURS = {
  coin: ["#d9a21b", "#f2cf62"],
  authority: ["#2a2e8a", "#6c72e0"],
  deed: ["#3f8f5a", "#9a7652"],
  key: ["#9c7b22", "#d8b54a"],
  banner: ["#2a2e8a", "#b3402a"],
  trophy: ["#b8871a", "#f0c94a"],
  wear: ["#4f5a76", "#8f9bb8"],
  face: ["#262c3a", "#8fb3d9"],
  hand: ["#7a5230", "#e8dcc8"],
};

/** An <svg> of `kind` ("coin", "deed", …); `authority` colours a coin as authority. */
export function glyph(kind, authority = false) {
  const art = ART[kind] || ART.coin;
  const [a, b] = COLOURS[authority ? "authority" : kind] || COLOURS.coin;
  const ns = "http://www.w3.org/2000/svg";
  const svg = document.createElementNS(ns, "svg");
  svg.setAttribute("viewBox", "0 0 12 12");
  svg.setAttribute("aria-hidden", "true");
  svg.setAttribute("shape-rendering", "crispEdges");
  art.forEach((row, y) => {
    [...row].forEach((ch, x) => {
      if (ch === ".") return;
      const r = document.createElementNS(ns, "rect");
      r.setAttribute("x", x);
      r.setAttribute("y", y);
      r.setAttribute("width", 1);
      r.setAttribute("height", 1);
      r.setAttribute("fill", ch === "#" ? a : b);
      svg.append(r);
    });
  });
  return svg;
}
